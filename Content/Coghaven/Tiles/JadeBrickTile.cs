using Cogpunk.Core.Templates;
using Microsoft.Xna.Framework;
using Terraria;
using Terraria.ID;
using Terraria.ModLoader;

namespace Cogpunk.Content.Coghaven.Tiles
{
	/// <summary>
	/// Jade Brick (2026-11-06): polished jade bricks in a staggered bond with a gilt stud here and there, the terrace and walls of Coghaven's palace. A building block (since the user's second request of 2026-11-06 the palace's floors are Palace Flagstone; jade bricks are crafted). Generated by <see cref="Generation.CoghavenPass"/>; seamless clump art from art/coghaven/make_coghaven_art.py.
	/// </summary>
	public class JadeBrickTile : CogpunkTile
	{
		public override void SetStaticDefaults() {
			TileID.Sets.GeneralPlacementTiles[Type] = false;   // later world-gen features (other mods) keep off the palace
			Main.tileSolid[Type] = true;
			Main.tileBlockLight[Type] = true;
			DustType = DustID.GemEmerald;
			HitSound = SoundID.Tink;
			AddMapEntry(new Color(58, 166, 118), CreateMapEntryName());
			RegisterItemDrop(ModContent.ItemType<Items.JadeBrick>());
		}
	}
}
