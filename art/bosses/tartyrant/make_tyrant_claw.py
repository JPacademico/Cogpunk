"""Source for the Tyrant armor's set-bonus claw (D4), restored 2026-11-06. Run from the repo root:

    python -P art/bosses/tartyrant/make_tyrant_claw.py

The user's 2026-11-06 rework of the Tyrant armor keeps "the tar claw effect" in the set bonus: the claw of 2026-10-29 (a
tar arm with a bone claw, Tar Tyrant's own enrage claw cut down to a player's size), which the 2026-11-03 summoner rework
had removed (commit 222cfdd holds it). Tar Tyrant's claw drawing is unchanged since then, so this renders it through the
boss generator's own claw_frames() at the 2026-10-29 scale and sequence (art/bosses/tartyrant/previous/
make_tartyrant_art_2026-10-29.py: TYRANT_CLAW_*), without touching any of the boss's sheets.

Outputs:
    Content/Bosses/TarTyrant/Armor/TyrantClaw.png        one column of 13 frames, 92x124 cells (2 px under each), the
                                                         bottom row on the ground: Warn x2, Rise x4, Grab x3, Sink x4
    Content/Bosses/TarTyrant/Armor/TyrantClawRigData.cs  the cell size and the frame runs, read by TyrantClaw.cs
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_tartyrant_art as tt  # noqa: E402

ROOT = os.getcwd()
ARMOR_OUT = "Content/Bosses/TarTyrant/Armor/"
TYRANT_CLAW_SCALE = 0.62
TYRANT_CLAW_W, TYRANT_CLAW_H = 46, 62
TYRANT_CLAW_SEQ = ("Warn", 2), ("Rise", 4), ("Grab", 3), ("Sink", 4)


def write_rig_data(path):
    n, parts = tt.runs("", TYRANT_CLAW_SEQ)
    lines = [
        "// <auto-generated> by art/bosses/tartyrant/make_tyrant_claw.py - do not edit by hand. </auto-generated>",
        "namespace Cogpunk.Content.Bosses.TarTyrant.Armor",
        "{",
        "\t/// <summary>The Tyrant armor's set-bonus claw (TyrantClaw.png: one column of equal cells, 2 px under each, the bottom",
        "\t/// row on the ground). Each sequence is Name0 .. Name0 + NameFrames - 1.</summary>",
        "\tpublic static class TyrantClawRigData",
        "\t{",
        "\t\tpublic const int Width = %d, Height = %d, FrameCount = %d;" % (TYRANT_CLAW_W * 2, TYRANT_CLAW_H * 2, n),
        "\t\tpublic const int %s;" % parts,
        "\t}",
        "}",
    ]
    with open(os.path.join(ROOT, path), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s" % path)


def main():
    frames = tt.claw_frames(TYRANT_CLAW_SCALE, TYRANT_CLAW_W, TYRANT_CLAW_H, TYRANT_CLAW_SEQ)
    tt.export(tt.vertical(frames), ARMOR_OUT + "TyrantClaw.png")
    write_rig_data(ARMOR_OUT + "TyrantClawRigData.cs")


if __name__ == "__main__":
    main()
